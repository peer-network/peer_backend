<?php

declare(strict_types=1);

/**
 * host.php — Stack P PHP-frontend entrypoint.
 *
 * Sits in front of the authoritative PHP backend, proxies every request
 * to it, and (when SHADOW_DISPATCH_FLAG=1) forks the same body+headers
 * to peergamma so we get a Rust-vs-PHP parity verdict per request.
 *
 * The fork is fire-and-forget *after the response is on the wire*:
 *
 *   1. Read the request (method, path, query, headers, raw body).
 *   2. POST/forward to PHP_BACKEND_URL synchronously — that's the
 *      authoritative leg the client is waiting on.
 *   3. Stream the PHP backend response back to the client.
 *   4. Call fastcgi_finish_request() — the client connection is closed
 *      from this point on, the FPM worker is the only one still running.
 *   5. If SHADOW_DISPATCH_FLAG=1 and a roll-of-the-dice falls under
 *      SHADOW_DISPATCH_PERCENT, fork to PEERGAMMA_URL, classify the
 *      response pair, and emit one OTLP span describing the verdict.
 *      Failures land in runtime-data/shadow-dlq/ for later replay.
 *
 * Latency budget (Plan_peer-hybrid-deployment.md §Telemetry): the fork
 * MUST NOT raise PHP p95 by more than ~10 ms. Steps 1–3 are exactly
 * what the legacy single-backend deploy does; step 4 is the only added
 * client-visible cost (negligible). Step 5 only burns extra worker time.
 *
 * Trace correlation: X-Request-Id is generated by stack-p's nginx (see
 * aelix infra/stack-p/nginx.conf) and propagated to both legs so the
 * PHP and peergamma traces are joinable in Tempo.
 *
 * Env contract (set by aelix nix/modules/stack-p.nix):
 *   PHP_BACKEND_URL          required, e.g. http://127.0.0.1:8892
 *   PEERGAMMA_URL            required when SHADOW_DISPATCH_FLAG=1
 *   SHADOW_DISPATCH_FLAG     "0" or "1"; off by default
 *   SHADOW_DISPATCH_PERCENT  0..100; percent of requests to fork
 *   OTEL_EXPORTER_OTLP_ENDPOINT  base URL for the local OTel collector
 *   SHADOW_OTLP_TRACES_ENDPOINT  override, default http://127.0.0.1:4318/v1/traces
 *   OTEL_SERVICE_NAME        defaults to peer-frontend
 *   OTEL_SERVICE_NAMESPACE   defaults to stack-p
 *   SHADOW_DLQ_DIR           defaults to runtime-data/shadow-dlq
 *   SHADOW_RUST_TIMEOUT_S    defaults to 5.0 (per-request peergamma cap)
 */

\ini_set('log_errors', '1');
\ini_set('error_log', dirname(__FILE__) . '/../runtime-data/logs/errorlog.txt');

require __DIR__ . '/../vendor/autoload.php';

use Fawaz\ShadowDispatch\CurlHttpForker;
use Fawaz\ShadowDispatch\Dlq;
use Fawaz\ShadowDispatch\OtlpEmitter;
use Fawaz\ShadowDispatch\ShadowDispatcher;
use Fawaz\ShadowDispatch\ShadowRequest;
use Fawaz\ShadowDispatch\ShadowResponse;

$startMicro = microtime(true);
$startUnixNano = (int) ($startMicro * 1e9);

// ── 1. Parse incoming request ────────────────────────────────────────
$method = $_SERVER['REQUEST_METHOD'] ?? 'GET';
$uri = $_SERVER['REQUEST_URI'] ?? '/';
$path = parse_url($uri, PHP_URL_PATH) ?: '/';
$query = parse_url($uri, PHP_URL_QUERY) ?: '';
$rawBody = file_get_contents('php://input') ?: '';

/** @var array<string,string> $headers */
$headers = [];
foreach ($_SERVER as $k => $v) {
    if (str_starts_with($k, 'HTTP_') && is_string($v)) {
        $name = strtolower(str_replace('_', '-', substr($k, 5)));
        $headers[$name] = $v;
    }
}
if (isset($_SERVER['CONTENT_TYPE'])) {
    $headers['content-type'] = (string) $_SERVER['CONTENT_TYPE'];
}
if (isset($_SERVER['CONTENT_LENGTH'])) {
    $headers['content-length'] = (string) $_SERVER['CONTENT_LENGTH'];
}

// X-Request-Id: trust nginx if it set one, else mint one.
$requestId = $headers['x-request-id'] ?? bin2hex(random_bytes(8));
$headers['x-request-id'] = $requestId;
header('X-Request-Id: ' . $requestId);

// GraphQL operation name lift, if this looks like a /graphql POST.
$graphqlOperationName = null;
if ($method === 'POST' && (str_contains($headers['content-type'] ?? '', 'application/json'))) {
    $decoded = json_decode($rawBody, true);
    if (is_array($decoded) && isset($decoded['operationName']) && is_string($decoded['operationName'])) {
        $graphqlOperationName = $decoded['operationName'];
    }
}

// ── 2. Forward to authoritative PHP backend ──────────────────────────
$phpBackendUrl = $_ENV['PHP_BACKEND_URL'] ?? $_SERVER['PHP_BACKEND_URL'] ?? '';
if ($phpBackendUrl === '') {
    http_response_code(500);
    header('Content-Type: text/plain');
    echo "host.php misconfigured: PHP_BACKEND_URL is unset\n";
    return;
}

$forwardUrl = rtrim($phpBackendUrl, '/') . $path;
if ($query !== '') {
    $forwardUrl .= '?' . $query;
}

$ch = curl_init($forwardUrl);
$forwardHeaders = [];
// Drop hop-by-hop headers that would break re-proxying.
$skip = ['host', 'connection', 'content-length', 'transfer-encoding', 'keep-alive', 'upgrade'];
foreach ($headers as $name => $value) {
    if (in_array($name, $skip, true)) {
        continue;
    }
    $forwardHeaders[] = $name . ': ' . $value;
}

$responseHeaders = [];
$responseBody = '';
$phpStart = microtime(true);
curl_setopt_array($ch, [
    CURLOPT_CUSTOMREQUEST => $method,
    CURLOPT_POSTFIELDS => $rawBody,
    CURLOPT_HTTPHEADER => $forwardHeaders,
    CURLOPT_RETURNTRANSFER => true,
    CURLOPT_TIMEOUT => 30,
    CURLOPT_CONNECTTIMEOUT => 5,
    CURLOPT_NOSIGNAL => 1,
    CURLOPT_HEADERFUNCTION => static function ($_curl, $headerLine) use (&$responseHeaders) {
        $len = strlen($headerLine);
        $colon = strpos($headerLine, ':');
        if ($colon !== false) {
            $name = strtolower(trim(substr($headerLine, 0, $colon)));
            $value = trim(substr($headerLine, $colon + 1));
            $responseHeaders[$name] = $value;
        }
        return $len;
    },
]);
$resp = curl_exec($ch);
$phpStatus = (int) curl_getinfo($ch, CURLINFO_RESPONSE_CODE);
$curlErr = curl_errno($ch);
curl_close($ch);
$phpLatencyMs = (microtime(true) - $phpStart) * 1000.0;

if ($resp === false || $curlErr !== 0 || $phpStatus === 0) {
    http_response_code(502);
    header('Content-Type: text/plain');
    echo "host.php: upstream PHP backend unreachable\n";
    return;
}

$responseBody = is_string($resp) ? $resp : '';

// ── 3. Stream PHP backend response back to client ────────────────────
http_response_code($phpStatus);
foreach ($responseHeaders as $name => $value) {
    // Skip the headers PHP writes itself, plus hop-by-hop noise.
    if (in_array($name, ['transfer-encoding', 'connection', 'content-length', 'keep-alive'], true)) {
        continue;
    }
    header($name . ': ' . $value, true);
}
// Make absolutely sure the correlation id is on the response.
header('X-Request-Id: ' . $requestId, true);
echo $responseBody;

// ── 4. Detach from client so the fork is invisible to p95 ────────────
if (function_exists('fastcgi_finish_request')) {
    fastcgi_finish_request();
}

// ── 5. Optionally fork to peergamma ──────────────────────────────────
$flagEnabled = (string) ($_ENV['SHADOW_DISPATCH_FLAG'] ?? $_SERVER['SHADOW_DISPATCH_FLAG'] ?? '0') === '1';
$percent = (int) ($_ENV['SHADOW_DISPATCH_PERCENT'] ?? $_SERVER['SHADOW_DISPATCH_PERCENT'] ?? 0);
$peergammaUrl = (string) ($_ENV['PEERGAMMA_URL'] ?? $_SERVER['PEERGAMMA_URL'] ?? '');

if (!$flagEnabled || $percent <= 0 || $peergammaUrl === '') {
    return;
}

try {
    $tracesEndpoint = (string) (
        $_ENV['SHADOW_OTLP_TRACES_ENDPOINT']
        ?? $_SERVER['SHADOW_OTLP_TRACES_ENDPOINT']
        ?? 'http://127.0.0.1:4318/v1/traces'
    );
    $serviceName = (string) ($_ENV['OTEL_SERVICE_NAME'] ?? $_SERVER['OTEL_SERVICE_NAME'] ?? 'peer-frontend');
    $serviceNs = (string) ($_ENV['OTEL_SERVICE_NAMESPACE'] ?? $_SERVER['OTEL_SERVICE_NAMESPACE'] ?? 'stack-p');
    $dlqDir = (string) (
        $_ENV['SHADOW_DLQ_DIR']
        ?? $_SERVER['SHADOW_DLQ_DIR']
        ?? (__DIR__ . '/../runtime-data/shadow-dlq')
    );
    $rustTimeoutS = (float) ($_ENV['SHADOW_RUST_TIMEOUT_S'] ?? $_SERVER['SHADOW_RUST_TIMEOUT_S'] ?? 5.0);

    $dispatcher = new ShadowDispatcher(
        new CurlHttpForker(),
        new OtlpEmitter($tracesEndpoint, $serviceName, $serviceNs),
        new Dlq($dlqDir),
        $peergammaUrl,
        $flagEnabled,
        $percent,
        $rustTimeoutS,
    );

    $req = new ShadowRequest(
        method: $method,
        path: $path,
        query: $query,
        headers: $headers,
        body: $rawBody,
        requestId: $requestId,
        startUnixNano: $startUnixNano,
        graphqlOperationName: $graphqlOperationName,
    );
    $phpDbWriteCount = isset($responseHeaders['x-db-write-count'])
        ? max(0, (int) $responseHeaders['x-db-write-count'])
        : 0;
    $phpResp = new ShadowResponse(
        status: $phpStatus,
        body: $responseBody,
        latencyMs: $phpLatencyMs,
        dbWriteCount: $phpDbWriteCount,
    );

    $dispatcher->dispatch($req, $phpResp);
} catch (\Throwable $e) {
    // Belt-and-braces: never let a shadow-side bug surface to the
    // client (we already finished the request) — just log and drop.
    error_log('host.php shadow dispatch failed: ' . $e->getMessage());
}
